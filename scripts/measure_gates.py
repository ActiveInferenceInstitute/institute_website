#!/usr/bin/env python3
"""Measure gate arms, then generate/check the single timing document."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs/gate-measurements.json"
DOCUMENT = ROOT / "docs/GATE_MEASUREMENTS.md"


def command_signature() -> str:
    digest = hashlib.sha256()
    files = [ROOT / "package.json", ROOT / "run.sh", *sorted((ROOT / "scripts").glob("*.py")),
             *sorted((ROOT / "scripts").glob("*.mjs")), ROOT / ".github/gnn-pin.json"]
    for path in files:
        digest.update(path.relative_to(ROOT).as_posix().encode() + b"\0" + path.read_bytes())
    return digest.hexdigest()


def exemplar_notes(data: dict) -> list[str]:
    """Say, per recorded arm, what its command does with the pinned exemplar."""
    notes = []
    for phase in ("before", "after"):
        command = data.get(phase, {}).get("gnn", {}).get("command", "")
        handling = ("receives pre-fetched exemplar bytes (`--exemplar`), so its time excludes that download"
                    if "--exemplar" in command.split()
                    else "fetches the pinned exemplar itself, so its time includes that download")
        notes.append(f"The GNN {phase} arm {handling}.")
    notes.append("Parser installation is excluded from both arms.")
    return notes


def render(data: dict) -> str:
    lines = ["# Gate measurements", "", "Generated by `python3 scripts/measure_gates.py --refresh`; do not hand-edit.",
             "Source observations: [gate-measurements.json](gate-measurements.json).", "",
             f"Host: {data['host']}. Node {data['node']}; Python {data['python']}.", "",
             "One local run per phase/arm; seconds are wall time, including command startup but excluding dependency acquisition.",
             "Before/after failures are partial runs, not comparable full-suite timings. No speedup is claimed.",
             "The baseline build/full ran outside the governed sandbox with the default temporary directory;",
             "the other observations use the vault's governed execution and a canonical temporary directory.",
             *exemplar_notes(data), "",
             "| Arm | Before (s) | Exit | After (s) | Exit |", "| --- | ---: | ---: | ---: | ---: |"]
    for arm in ("lint", "fast", "full", "docs", "gnn", "build", "browser"):
        row = [arm]
        for phase in ("before", "after"):
            result = data.get(phase, {}).get(arm)
            row.extend([f"{result['seconds']:.3f}", str(result['exit_code'])] if result else ["not measured", "—"])
        lines.append("| " + " | ".join(row) + " |")
    lines.extend(["", "## Scope", "", "`fast` selects the existing i18n helper tests. `full` retains the offline checks;",
                  "indexability regression modules run once via Python discovery, not again in `check:indexability`.",
                  "Lint/docs are independently runnable and included in full. Browser retains the original calendar,",
                  "newsletter and quick-interaction sequence; a first-step failure prevents later steps from running.",
                  "There is no repository type-checker or manuscript directory; no type or manuscript arm is invented.", "",
                  "Before: the complete build/full/browser sequence ran in every CI matrix entry.",
                  "After: one build-and-check job owns that sequence; compatibility jobs run lint/fast only.",
                  "This removes duplicated work but does not establish a measured CI speedup. Hosted Actions is billing-locked.", "",
                  "## Verification boundary", "", "A nonzero exit is not a passing gate. Consult the PR for the exact failing command and reason.",
                  "Local timings are not hosted CI, deployment or publication proof.", ""])
    return "\n".join(lines)


def check_index() -> None:
    index = ROOT / "docs/documentation-index.md"
    text = index.read_text()
    expected = {p.relative_to(index.parent).as_posix() for p in index.parent.rglob("*.md")}
    linked = set(re.findall(r"\]\(([^)#]+)(?:#[^)]*)?\)", text))
    missing = expected - linked
    if missing:
        raise SystemExit("Missing documentation-index entries: " + ", ".join(sorted(missing)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--measure", action="store_true")
    mode.add_argument("--refresh", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--before", type=Path)
    parser.add_argument("--after", type=Path)
    parser.add_argument("--arms", nargs="+", default=["lint", "fast", "full", "docs", "gnn", "browser"])
    parser.add_argument("--exemplar", type=Path)
    args = parser.parse_args()
    if args.measure:
        if not args.output:
            parser.error("--measure requires --output outside the public checkout")
        output = args.output.resolve()
        if output.is_relative_to(ROOT):
            parser.error("measurement logs/evidence must be outside the public checkout")
        results = {}
        for arm in args.arms:
            command = [str(ROOT / "run.sh"), arm]
            if arm == "gnn" and args.exemplar:
                command += ["--exemplar", str(args.exemplar.resolve())]
            started = time.perf_counter()
            with output.with_name(output.stem + "-" + arm + ".log").open("w") as log:
                result = subprocess.run(command, cwd=ROOT, stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT)
            results[arm] = {"seconds": round(time.perf_counter() - started, 3), "exit_code": result.returncode,
                            "command": "./run.sh " + arm + (" --exemplar PINNED_FILE" if arm == "gnn" and args.exemplar else "")}
            output.write_text(json.dumps(results, indent=2) + "\n")
            print(arm, json.dumps(results[arm]), flush=True)
        return
    if args.refresh:
        data = json.loads(EVIDENCE.read_text()) if EVIDENCE.exists() else {
            "host": f"{platform.system()} {platform.release()} {platform.machine()}",
            "node": subprocess.check_output(["node", "--version"], text=True, stdin=subprocess.DEVNULL).strip(),
            "python": platform.python_version()}
        for phase, path in (("before", args.before), ("after", args.after)):
            if path:
                data[phase] = json.loads(path.read_text())
        data["refreshed_at"] = datetime.now(timezone.utc).isoformat()
        data["command_source_sha256"] = command_signature()
        EVIDENCE.write_text(json.dumps(data, indent=2) + "\n")
        DOCUMENT.write_text(render(data))
    else:
        data = json.loads(EVIDENCE.read_text())
        if data["command_source_sha256"] != command_signature():
            raise SystemExit("Gate command/test sources changed; measure affected arms and refresh gate measurements")
        if DOCUMENT.read_text() != render(data):
            raise SystemExit("Generated gate measurements are stale; run scripts/measure_gates.py --refresh")
        check_index()
        print("Gate measurements and documentation index are current.")


if __name__ == "__main__":
    main()
